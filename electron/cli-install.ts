// #115: the first writable PATH dir was an rvm gemset, so the shim vanished on
// `rvm use` and a dead copy further down PATH took over unseen.

import * as path from "node:path";
import { COMMAND_NOT_FOUND_EXIT_CODE } from "./constants";

/** Dirs a version manager swaps or regenerates per version (`rbenv rehash`
 *  wipes its shims), so a shim there drops off PATH on the next switch. */
const VERSION_MANAGED = [
  "/.rvm/",
  "/.rbenv/",
  "/.pyenv/",
  "/.nvm/",
  "/.asdf/",
  "/.fnm/",
  "/.gem/",
  "/mise/installs/",
  "/mise/shims/",
  "/fnm_multishells/",
  "/.local/share/fnm/",
  "/.nodenv/",
  "/.rubies/",
  "/miniconda3/",
  "/anaconda3/",
  "/.conda/",
  "/node_modules/.bin/",
];

const normalizeDir = (dir: string) => path.normalize(dir).replace(/\/+$/, "");

export function isVersionManagedDir(dir: string): boolean {
  const normalized = `${normalizeDir(dir)}/`;
  return VERSION_MANAGED.some((marker) => normalized.includes(marker));
}

export interface InstallDirChoice {
  dir: string;
  onPath: boolean;
}

/** ~/.local/bin when PATH has it and it is writable; else the first writable
 *  PATH dir no version manager owns; else ~/.local/bin flagged off-PATH. */
export function chooseCliInstallDir(
  pathEntries: string[],
  home: string,
  isWritableDir: (dir: string) => boolean,
): InstallDirChoice {
  const preferred = path.join(home, ".local", "bin");
  if (
    pathEntries.some((entry) => normalizeDir(entry) === preferred) &&
    isWritableDir(preferred)
  ) {
    return { dir: preferred, onPath: true };
  }
  const stable = pathEntries.find(
    (entry) => !isVersionManagedDir(entry) && isWritableDir(entry),
  );
  if (stable) return { dir: stable, onPath: true };
  return { dir: preferred, onPath: false };
}

export interface AyaCopy {
  path: string;
  /** Generated by Aya (current or legacy shim), so safe to rewrite or remove. */
  ours: boolean;
  /** Ours, and none of its targets is executable any more. */
  broken: boolean;
}

/** The legacy `exec "<path>" "$@"` shim has no marker, so it only counts as
 *  ours when it execs an `aya` - a foreign wrapper stays foreign. */
export function ayaShimTargets(content: string): string[] {
  const targets = parseShimTargets(content);
  return targets.every((target) => path.basename(target) === "aya")
    ? targets
    : [];
}

/** The OS cannot exec inside .asar (#39: "Not a directory"), but Electron's
 *  patched fs reads into archives, so an X_OK probe from the app passes. */
export function insideAsarArchive(target: string): boolean {
  return path
    .normalize(target)
    .split(path.sep)
    .slice(0, -1)
    .some((segment) => segment.endsWith(".asar"));
}

export interface CliInstallPlan {
  rewrite: string[];
  remove: string[];
}

/** Our other copies, after `target` is written: removed from version-managed
 *  dirs, rewritten elsewhere. Foreign scripts are never touched. */
export function planCliInstall(copies: AyaCopy[], target: string): CliInstallPlan {
  // Removing only helps when the shell then runs `target`; otherwise it would
  // leave no aya on PATH, or hand PATH to a foreign one (#120 review).
  const targetAt = copies.findIndex((copy) => copy.path === target);
  const targetWins =
    targetAt >= 0 && copies.slice(0, targetAt).every((copy) => copy.ours);
  const plan: CliInstallPlan = { rewrite: [], remove: [] };
  for (const copy of copies) {
    if (!copy.ours || copy.path === target) continue;
    if (targetWins && isVersionManagedDir(path.dirname(copy.path))) plan.remove.push(copy.path);
    else plan.rewrite.push(copy.path);
  }
  return plan;
}

export const offPathNote = (choice: InstallDirChoice) =>
  choice.onPath ? "" : ` - ${choice.dir} is not on your PATH, add it to use the command`;

/** The Settings line for the `aya` command. `copies` is in PATH order, so the
 *  first one is what a shell runs; the rest are shadowed. */
export function describeCliStatus(
  copies: AyaCopy[],
  choice: InstallDirChoice,
): string | undefined {
  const active = copies[0];
  if (!active) return `Install to ${path.join(choice.dir, "aya")}${offPathNote(choice)}`;

  const staleBelow = copies.slice(1).filter((copy) => copy.broken);
  const staleNote =
    staleBelow.length > 0
      ? `a dead copy further down PATH takes over if it disappears (${staleBelow
          .map((copy) => copy.path)
          .join(", ")})`
      : undefined;
  if (!active.ours) {
    const foreign = `${active.path} comes first on PATH and was not installed by Aya.`;
    return staleNote ? `${foreign} Also, ${staleNote} - click Reinstall to repair.` : foreign;
  }
  const notes: string[] = [];
  if (active.broken) {
    notes.push("it points at a moved or renamed Aya.app");
  } else if (isVersionManagedDir(path.dirname(active.path))) {
    notes.push(
      "that directory belongs to a version manager and drops off PATH when you switch versions",
    );
  }
  if (staleNote) notes.push(staleNote);
  if (notes.length === 0) return undefined;
  return `Installed at ${active.path}, but ${notes.join("; and ")} - click Reinstall to repair.`;
}

// The installed `aya` command is a tiny shim that execs the CLI bundled
// inside the packaged app. The bundle path is baked at install time, so
// moving or renaming Aya.app used to kill the shim with sh's cryptic
// "No such file or directory" (follow-up on #42). The generated script now
// self-heals via the default install location and otherwise points the user
// at the repair path; parseShimTargets lets cliStatus() detect a dead shim
// and surface "Reinstall" in Settings.


// Marker baked into every shim we generate; parseShimTargets refuses to parse
// AYA_CLI lines from scripts that lack it, so foreign scripts that merely
// contain a similar-looking string are never misclassified as our shim.
const SHIM_MARKER = "Generated by Aya";

/** POSIX single-quote escaping: wrap in ' and turn embedded ' into '\''.
 *  Single quotes inhibit ALL shell expansion ($, backticks, !), which
 *  double-quoted JSON.stringify output does not - a path containing $HOME
 *  would be expanded at shim runtime and exec the wrong file. */
function shQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** POSIX-sh shim that prefers the baked CLI path, falls back to the default
 *  install location (when one exists and differs), and otherwise explains
 *  how to repair instead of failing cryptically. Paths are embedded
 *  single-quoted so no shell expansion can mangle them at runtime. */
export function renderCliShim(
  primary: string,
  fallback: string | null,
): string {
  const lines = [
    "#!/bin/sh",
    `# ${SHIM_MARKER} (Settings -> aya command-line tool).`,
    `AYA_CLI=${shQuote(primary)}`,
  ];
  if (fallback && fallback !== primary) {
    lines.push(
      `if [ ! -x "$AYA_CLI" ]; then AYA_CLI=${shQuote(fallback)}; fi`,
    );
  }
  lines.push(
    'if [ ! -x "$AYA_CLI" ]; then',
    '  echo "aya: cannot find Aya.app (moved or renamed?). Open Aya -> Settings -> aya command-line tool -> Reinstall." >&2',
    `  exit ${COMMAND_NOT_FOUND_EXIT_CODE}`,
    "fi",
    'exec "$AYA_CLI" "$@"',
    "",
  );
  return lines.join("\n");
}

/** Candidate CLI paths a previously-installed shim points at, in order.
 *  Understands the current single-quoted AYA_CLI=... form (only when the
 *  shim carries our marker comment, so foreign scripts that merely contain a
 *  lookalike string parse to []) and the legacy single-line
 *  `exec "<path>" "$@"` form from the first #42 fix. */
export function parseShimTargets(content: string): string[] {
  const targets: string[] = [];
  if (content.includes(SHIM_MARKER)) {
    for (const match of content.matchAll(
      /AYA_CLI='((?:[^']|'\\'')*)'(?:;|$)/gm,
    )) {
      targets.push(match[1].replaceAll(`'\\''`, "'"));
    }
  }
  if (targets.length === 0) {
    // The WHOLE file must be the two-line legacy shim: a user's own wrapper
    // that merely ends in a similar exec line is not ours (#120 review).
    const legacy = content.match(/^#!\/bin\/sh\nexec ("(?:[^"\\]|\\.)*") "\$@"\n?$/);
    if (legacy) {
      try {
        targets.push(JSON.parse(legacy[1]) as string);
      } catch {
        // not ours
      }
    }
  }
  return targets;
}

/** Where the CLI lives when Aya sits in the default install location - the
 *  shim's self-heal target after the app was moved back / renamed / updated.
 *  Only macOS has a stable well-known location; elsewhere there is none. */
export function defaultInstallAyaCliPath(
  platform: NodeJS.Platform,
): string | null {
  if (platform !== "darwin") return null;
  return path.join(
    "/Applications",
    "Aya.app",
    "Contents",
    "Resources",
    "app.asar.unpacked",
    "bin",
    "aya",
  );
}
